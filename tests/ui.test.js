import {test} from 'node:test';
import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

test('main offline research flows render without runtime errors', async () => {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const bundle = await build({entryPoints: [path.join(root, 'src/main.jsx')], bundle: true, write: false, format: 'iife', loader: {'.css': 'empty'}, define: {'import.meta.env.BASE_URL': '"/"'}, logLevel: 'silent'});
  const dom = new JSDOM('<div id="root"></div>', {url: 'http://localhost:4173', runScripts: 'outside-only', pretendToBeVisual: true});
  const w = dom.window; const errors = [];
  w.addEventListener('error', event => errors.push(event.message));
  w.scrollTo = () => {}; w.HTMLElement.prototype.scrollIntoView = () => {};
  w.fetch = async url => { const file = path.join(root, 'public', String(url).replace(/^\//, '')); return {ok: fs.existsSync(file), json: async () => JSON.parse(fs.readFileSync(file))}; };
  w.eval(bundle.outputFiles[0].text);
  let waitStep = 0;
  const wait = async predicate => { const step = ++waitStep; for (let index = 0; index < 500; index += 1) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 20)); } throw Error(`UI condition timed out at step ${step}`); };
  const click = text => { const button = [...w.document.querySelectorAll('button')].find(node => node.textContent.includes(text)); assert(button, `button ${text}`); button.click(); return button; };

  await wait(() => w.document.body.textContent.includes('البقرة'));
  click('درباره برنامه'); await wait(() => w.document.body.textContent.includes('مشخصات نرم‌افزار'));
  assert(w.document.body.textContent.includes('امیررضا نصیری'));
  assert(w.document.body.textContent.includes('Tanzil Uthmani'));
  click('حمایت از توسعه'); await wait(() => w.document.body.textContent.includes('۵۰۲۲'));
  assert(w.document.body.textContent.includes('این حمایت کاملاً اختیاری است'));
  click('تنظیمات'); await wait(() => w.document.body.textContent.includes('رسم‌الخط و اندازهٔ قرآن'));
  assert.equal(w.document.querySelectorAll('.font-picker [role="radio"]').length, 5);
  click('مشابه‌یاب'); await wait(() => w.document.body.textContent.includes('موتور مشابه‌یاب آیات جامع التفاسیر منصور'));
  assert(w.document.querySelector('.similarity-form textarea'));
  click('احادیث مرتبط'); await wait(() => w.document.body.textContent.includes('منابع حدیثی آفلاین جامع التفاسیر منصور'));
  assert(w.document.querySelector('.source-controls'));
  click('فهرست منابع و مآخذ علمی برنامه'); await wait(() => w.document.querySelector('.bibliography-sheet[role="dialog"]'));
  assert(w.document.body.textContent.includes('هنوز بستهٔ حدیثی نصب نشده است'));
  w.document.querySelector('[aria-label="بستن فهرست مآخذ"]').click();
  await wait(() => !w.document.querySelector('.bibliography-sheet'));
  click('یادداشت‌ها'); await wait(() => w.document.body.textContent.includes('یادداشت و پژوهش'));
  click('پژوهش تازه'); await wait(() => w.document.querySelector('.rich-editor'));
  assert(w.document.querySelector('[aria-label="قالب‌بندی متن"]'));
  click('کتابخانه'); await wait(() => w.document.body.textContent.includes('التفسير الميسر'));
  click('التفسير الميسر'); await wait(() => w.document.querySelector('.tafsir-entry-list article'));
  assert(w.document.body.textContent.includes('گروهی از علمای تفسیر'));
  w.document.querySelector('[aria-label="صفحه اصلی قرآن"]').click();
  await wait(() => w.document.body.textContent.includes('فهرست سوره'));
  click('البقرة'); await wait(() => w.document.body.textContent.includes('صفحات قرآن'));
  click('نمایش آیه‌به‌آیه'); await wait(() => w.document.querySelector('.verse-info-button'));
  w.document.querySelector('.verse-info-button').click(); await wait(() => w.document.querySelector('[role="dialog"]'));
  [...w.document.querySelectorAll('.source-tabs button')].find(button => button.textContent.trim() === 'تفسیر').click();
  await wait(() => w.document.querySelector('.verse-tafsir-box'));
  assert.equal(w.document.querySelectorAll('.tafsir-scroll-tabs [role="tab"]').length, 1);
  assert.deepEqual(errors, []);
  dom.window.close();
});
